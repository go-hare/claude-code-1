/** densable `CM` spell. */
function confusableSpell(ch: string): string {
  if (/^[a-z]$/.test(ch)) return `[${latinLetterClass(ch)}]`
  if (ch === '-' || ch === '_') return CONNECTOR_SPELL
  if (/^[0-9]$/.test(ch)) return ch
  throw new Error(
    'confusableTagScrubPattern: tag names are lowercase [a-z0-9_-]',
  )
}

/** densable `CM` — `U` with `g$` filler and spell. */
function cmPattern(
  tags: readonly string[],
  tailFor?: (parts: CmTailParts) => string,
): RegExp {
  const brackets = bracketClasses()
  const letterFiller = [...'abcdefghijklmnopqrstuvwxyz']
    .map(latinLetterClass)
    .join('')
  return buildTagOpenPattern({
    tags: [...tags],
    closeOnly: false,
    fillerClass: `${brackets.filler}${letterFiller}`,
    spell: confusableSpell,
    tail: tailFor?.({
      name: NAME_CLASS,
      close: brackets.close,
      colon: COLON_CLASS,
    }),
  })
}

