function latinLetterClass(letter: string): string {
  if (!/^[a-z]$/.test(letter)) {
    throw new Error(
      'latinLetterConfusableClass: expected one ASCII lowercase letter',
    )
  }
  const codes = LATIN_LETTER_CODES[letter]
  return codes === undefined ? letter : String.fromCodePoint(...codes)
}

